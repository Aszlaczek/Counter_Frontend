import { beforeEach, expect, it, vi } from 'vitest';
import { render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { MemoryRouter, Route, Routes } from 'react-router-dom';
import ExtraHoursCreate from '../src/pages/ExtraHoursCreate';
import ExtraHoursEdit from '../src/pages/ExtraHoursEdit';
import { personService } from '../src/services/personService';
import { extraHoursService } from '../src/services/extraHoursService';
vi.mock('../src/services/personService', () => ({ personService: { getAllRecords: vi.fn(), create: vi.fn() } }));
vi.mock('../src/services/extraHoursService', () => ({ extraHoursService: { create: vi.fn(), update: vi.fn(), getById: vi.fn() } }));
const person = { id: 1, name: 'Jan', surname: 'Nowak', faculty: '', is_working: true, created_by_id: 1, created_at: '', updated_at: '' };
beforeEach(() => { vi.clearAllMocks(); vi.mocked(personService.getAllRecords).mockResolvedValue([person]); });
it('adds a person inline, preserves the draft, selects the person and submits a short departure', async () => {
  const user = userEvent.setup();
  vi.mocked(personService.create).mockResolvedValue({ ...person, id: 2, name: 'Anna' });
  render(<MemoryRouter><ExtraHoursCreate /></MemoryRouter>);
  await screen.findByRole('option', { name: 'Jan Nowak' });
  await user.type(screen.getByLabelText('Minuty (0-59)'), '30');
  await user.selectOptions(screen.getByLabelText(/Rodzaj wpisu/), 'departure');
  await user.click(screen.getByRole('button', { name: '+ Dodaj nową osobę tutaj' }));
  await user.type(screen.getByLabelText('Imię *'), 'Anna');
  await user.type(screen.getByLabelText('Nazwisko *'), 'Nowak');
  await user.click(screen.getByRole('button', { name: 'Dodaj osobę' }));
  await waitFor(() => expect(screen.getByLabelText('Osoba *')).toHaveValue('2'));
  expect(screen.getByLabelText('Minuty (0-59)')).toHaveValue(30);
  await user.click(screen.getByRole('button', { name: 'Dodaj wpis' }));
  await waitFor(() => expect(extraHoursService.create).toHaveBeenCalledWith(expect.objectContaining({ person_id: 2, hours: -0, minutes: -30 })));
});
it('edits a negative record and sends explicit zero when hours are cleared', async () => {
  const user = userEvent.setup();
  vi.mocked(extraHoursService.getById).mockResolvedValue({ id: 9, person_id: 1, hours: -1, minutes: -30, date: '2024-03-31', description: null, created_by_id: 1, created_at: '', updated_at: '', edited_by_id: null });
  render(<MemoryRouter initialEntries={['/extra-hours/9/edit']}><Routes><Route path="/extra-hours/:id/edit" element={<ExtraHoursEdit />} /><Route path="/extra-hours" element={<p>Lista</p>} /></Routes></MemoryRouter>);
  await screen.findByDisplayValue('1');
  expect(screen.getByLabelText(/Rodzaj wpisu/)).toHaveValue('departure');
  await user.clear(screen.getByLabelText('Godziny'));
  await user.selectOptions(screen.getByLabelText(/Rodzaj wpisu/), 'overtime');
  await user.click(screen.getByRole('button', { name: 'Zapisz zmiany' }));
  await waitFor(() => expect(extraHoursService.update).toHaveBeenCalledWith(9, expect.objectContaining({ hours: 0, minutes: 30 })));
});
